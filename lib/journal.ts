export function getPost(slug: string): JournalPost | undefined {
  return JOURNAL_POSTS.find((p) => p.slug === slug);
}

export function getPostsByService(service: Service): JournalPost[] {
  return JOURNAL_POSTS.filter((p) => p.services.includes(service));
}

export function isService(value: string | undefined): value is Service {
  return value === "frozen" || value === "bento" || value === "catering" || value === "common";
}

export function getRelatedPosts(
  slug: string,
  limit = 3
): JournalPost[] {
  const current = getPost(slug);
  if (!current) return JOURNAL_POSTS.slice(0, limit);
  // Score: shared primary service > shared category > shared tag > other
  const primary = current.services[0];
  const scored = JOURNAL_POSTS.filter((p) => p.slug !== slug).map((p) => {
    let score = 0;
    if (p.services.includes(primary)) score += 4;
    for (const s of current.services) if (p.services.includes(s)) score += 1;
    if (p.cat === current.cat) score += 2;
    const sharedTags = (current.tags ?? []).filter((t) =>
      (p.tags ?? []).includes(t)
    ).length;
    score += sharedTags;
    return { post: p, score };
  });
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.post);
}
